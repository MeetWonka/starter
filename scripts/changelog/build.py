#!/usr/bin/env python3
"""Build the public changelog pages from the release files in entries/.

Source of truth: the internal WonkaChat changelog in Odoo Knowledge
(article "WonkaChat Changelog", one child article per release). Those notes are
written for the team and mention internal work (Config PRs, secrets, preview
environments, feature flags). Each release is therefore rewritten for customers
in entries/YYYY-MM-DD.yaml, in en, fr and nl, before being published here.

Adding a release:
  1. Copy the latest entries/*.yaml, rename it to the release date.
  2. Rewrite the Odoo notes for customers. Leave out internal changes, anything
     only Wonka or a feature flag can see, infrastructure and vendor details,
     and exploitable security details (say what got safer, not what was open).
  3. python3 scripts/changelog/build.py

Release file format:
  date: 2026-10-14
  odoo_article: 3021            # Odoo Knowledge id, for traceability
  en:
    summary: optional one-line summary
    new: ["**Title**: text", ...]
    improved: [...]
    fixed: [...]
    security: [...]
    note: optional closing paragraph
  fr: {...same keys...}
  nl: {...same keys...}
"""

import sys
from datetime import date
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
LANGS = ("en", "fr", "nl")
SECTIONS = ("new", "improved", "fixed", "security")

MONTHS = {
    "en": "January February March April May June July August September October November December",
    "fr": "janvier février mars avril mai juin juillet août septembre octobre novembre décembre",
    "nl": "januari februari maart april mei juni juli augustus september oktober november december",
}

T = {
    "en": {
        "title": "Changelog",
        "description": "What's new in WonkaChat: new features, improvements and fixes, release by release.",
        "intro": "The latest WonkaChat updates, newest first.",
        "sections": {
            "new": "✨ New",
            "improved": "🔧 Improved",
            "fixed": "🐛 Fixed",
            "security": "🔒 Security and reliability",
        },
    },
    "fr": {
        "title": "Journal des modifications",
        "description": "Les nouveautés de WonkaChat : nouvelles fonctionnalités, améliorations et corrections, version par version.",
        "intro": "Les dernières mises à jour de WonkaChat, de la plus récente à la plus ancienne.",
        "sections": {
            "new": "✨ Nouveautés",
            "improved": "🔧 Améliorations",
            "fixed": "🐛 Corrections",
            "security": "🔒 Sécurité et fiabilité",
        },
    },
    "nl": {
        "title": "Wijzigingslogboek",
        "description": "Wat is er nieuw in WonkaChat: nieuwe functies, verbeteringen en oplossingen, per release.",
        "intro": "De nieuwste updates van WonkaChat, de meest recente eerst.",
        "sections": {
            "new": "✨ Nieuw",
            "improved": "🔧 Verbeterd",
            "fixed": "🐛 Opgelost",
            "security": "🔒 Beveiliging en betrouwbaarheid",
        },
    },
}


def label(d: date, lang: str) -> str:
    month = MONTHS[lang].split()[d.month - 1]
    if lang == "en":
        return f"{month} {d.day}, {d.year}"
    day = "1er" if lang == "fr" and d.day == 1 else d.day
    return f"{day} {month} {d.year}"


def attr(text: str) -> str:
    return text.replace('"', "&quot;")


def render(lang: str, releases: list) -> str:
    t = T[lang]
    out = [
        "---",
        f'title: "{t["title"]}"',
        f'description: "{t["description"]}"',
        'rss: true',
        "---",
        "",
        "{/* Generated by scripts/changelog/build.py from scripts/changelog/entries/. Do not edit by hand. */}",
        "",
        t["intro"],
        "",
    ]
    for rel in releases:
        content = rel[lang]
        present = [s for s in SECTIONS if content.get(s)]
        tags = ", ".join(f'"{attr(t["sections"][s].split(" ", 1)[1])}"' for s in present)
        desc = f' description="{attr(content["summary"])}"' if content.get("summary") else ""
        out.append(f'<Update label="{label(rel["date"], lang)}"{desc} tags={{[{tags}]}}>')
        for s in present:
            out += [f"### {t['sections'][s]}", ""]
            out += [f"- {item}" for item in content[s]]
            out.append("")
        if content.get("note"):
            out += [f"<Note>{content['note']}</Note>", ""]
        out += ["</Update>", ""]
    return "\n".join(out)


def load_releases() -> list:
    releases = []
    for path in sorted((HERE / "entries").glob("*.yaml")):
        rel = yaml.safe_load(path.read_text())
        if not isinstance(rel.get("date"), date):
            sys.exit(f"{path.name}: 'date' must be YYYY-MM-DD")
        for lang in LANGS:
            content = rel.get(lang)
            if not content:
                sys.exit(f"{path.name}: missing '{lang}' translation")
            unknown = set(content) - set(SECTIONS) - {"summary", "note"}
            if unknown:
                sys.exit(f"{path.name} ({lang}): unknown keys {sorted(unknown)}")
            if not any(content.get(s) for s in SECTIONS):
                sys.exit(f"{path.name} ({lang}): no changes listed")
        releases.append(rel)
    return sorted(releases, key=lambda r: r["date"], reverse=True)


def main() -> None:
    releases = load_releases()
    for lang in LANGS:
        path = ROOT / lang / "updates" / "changelog.mdx"
        path.write_text(render(lang, releases))
        print(f"Wrote {path.relative_to(ROOT)} ({len(releases)} releases)")


if __name__ == "__main__":
    main()
